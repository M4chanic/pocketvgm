// HuC6280 PSG (PC Engine / TurboGrafx-16) — 6 каналов волновой таблицы.
//
// Своё, по открытому описанию регистров ($0800-$0809). Готового Verilog
// не нашлось: в ядрах PC Engine эта часть написана на VHDL, а её нам не
// прожевать Verilator'ом, на котором стоит вся проверка проекта.
//
// Каналы обсчитываются по очереди, один за такт clk: волновая память
// одна на все шесть (6 x 32 x 5 бит) и читается по одному отсчёту, иначе
// 960 триггеров ушли бы в логику. Полный проход укладывается в 6 тактов
// clk и происходит по каждому cen, то есть на частоте чипа.
//
// LFO: канал 1 модулирует частоту канала 0 и при этом сам молчит. Модель
// снята с эталонной реализации (libvgm, emu/cores/c6280_mame.c), а не
// выведена из описания регистров.
module huc6280_psg (
    input  wire               clk,
    input  wire               cen,      // разрешение такта на частоте чипа
    input  wire               rst,
    input  wire               wr,
    input  wire        [3:0]  addr,     // $0800-$0809 -> 0..9
    input  wire        [7:0]  din,
    output reg  signed [15:0] snd_left  = 0,
    output reg  signed [15:0] snd_right = 0
);

  // ------------------------------------------------------------------
  // Регистры
  reg  [2:0] ch_sel = 0;
  reg  [3:0] main_l = 0, main_r = 0;

  reg [11:0] freq   [0:7];
  reg  [4:0] vol    [0:7];
  reg        ch_on  [0:7];
  reg        ch_dda [0:7];
  reg  [3:0] bal_l  [0:7];
  reg  [3:0] bal_r  [0:7];
  reg  [4:0] dda    [0:7];

  reg [11:0] cnt    [0:7];
  reg  [4:0] step   [0:7];
  reg  [4:0] wr_idx [0:7];

  // шум — только каналы 4 и 5
  reg        noise_en [0:7];
  reg  [4:0] noise_fq [0:7];
  reg [11:0] noise_cnt[0:7];
  reg [17:0] lfsr     [0:7];

  reg [4:0] wave_ram[0:191];

  // LFO: $08 — множитель частоты источника, $09 — бит 7 сброс, биты 1:0
  // глубина (0 выключено, 1/2/3 -> сдвиг 0/2/4)
  reg [7:0] lfo_freq = 0;
  reg [7:0] lfo_ctrl = 0;
  // Отсчёт канала-источника, снятый на проходе обхода: отдельный порт
  // чтения волновой памяти обошёлся бы дороже, а свежести хватает —
  // полный проход укладывается в шесть тактов clk, cen намного реже.
  reg [4:0] lfo_wave = 5'd16;

  integer i;

  // ------------------------------------------------------------------
  // Запись регистров
  always @(posedge clk) begin
    if (rst) begin
      ch_sel <= 0;
      main_l <= 0;
      main_r <= 0;
      lfo_freq <= 0;
      lfo_ctrl <= 0;
      for (i = 0; i < 6; i = i + 1) begin
        freq[i]   <= 0;
        vol[i]    <= 0;
        ch_on[i]  <= 0;
        ch_dda[i] <= 0;
        bal_l[i]  <= 4'hF;
        bal_r[i]  <= 4'hF;
        dda[i]      <= 0;
        wr_idx[i]   <= 0;
        noise_en[i] <= 0;
        noise_fq[i] <= 0;
      end
    end else if (wr) begin
      case (addr)
        4'h0: ch_sel <= din[2:0];
        4'h1: {main_l, main_r} <= din;
        4'h2: freq[ch_sel][7:0]  <= din;
        4'h3: freq[ch_sel][11:8] <= din[3:0];
        4'h4: begin
          // сброс индекса записи волны в момент выключения канала —
          // так рипы заливают таблицу с начала
          if (!din[7]) wr_idx[ch_sel] <= 0;
          ch_on[ch_sel]  <= din[7];
          ch_dda[ch_sel] <= din[6];
          vol[ch_sel]    <= din[4:0];
        end
        4'h5: {bal_l[ch_sel], bal_r[ch_sel]} <= din;
        4'h6: begin
          if (ch_dda[ch_sel]) begin
            dda[ch_sel] <= din[4:0];
          end else begin
            wave_ram[{ch_sel, wr_idx[ch_sel]}] <= din[4:0];
            wr_idx[ch_sel] <= wr_idx[ch_sel] + 1'b1;
          end
        end
        4'h7: if (ch_sel >= 3'd4) begin
          noise_en[ch_sel] <= din[7];
          noise_fq[ch_sel] <= din[4:0];
        end
        4'h8: lfo_freq <= din;
        4'h9: lfo_ctrl <= din;
        default: ;
      endcase
    end
  end

  // ------------------------------------------------------------------
  // Шаг частоты: период 0 читается как 4096
  // ------------------------------------------------------------------
  // LFO. Канал 1 — источник, канал 0 — приёмник; пока LFO включён, сам
  // канал 1 не звучит. Эталон (c6280_mame.c) считает так:
  //
  //   период источника  = (freq[1] * lfo_freq) & 0xFFF
  //   период приёмника  = (freq[0] + ((отсчёт_ист - 16) << сдвиг)) & 0xFFF
  //   сдвиг = ((ctrl & 3) - 1) * 2, то есть 0, 2 или 4
  //
  // Бит 7 регистра $09 держит источник в нуле и отключает модуляцию.
  wire lfo_on  = lfo_ctrl[1:0] != 2'd0;
  wire lfo_rst = lfo_ctrl[7];
  wire [2:0] lfo_sh = {lfo_ctrl[1:0] - 2'd1, 1'b0};      // 0, 2, 4
  wire signed [5:0] lfo_centred = {1'b0, lfo_wave} - 6'sd16;
  wire signed [11:0] lfo_off = $signed({{6{lfo_centred[5]}}, lfo_centred}) <<< lfo_sh;
  wire [19:0] lfo_prod = freq[1] * {12'd0, lfo_freq};

  // Периоды, с которыми перезаряжаются счётчики каналов 0 и 1
  wire [11:0] per0 = (lfo_on && !lfo_rst) ? (freq[0] + lfo_off[11:0]) : freq[0];
  wire [11:0] per1 = lfo_on ? lfo_prod[11:0] : freq[1];

  // Счётчики частоты и шума живут только здесь: регистр, присвоенный в
  // двух always-блоках, — два драйвера, и Quartus такое отвергает
  // (Verilator для массивов молчит, поэтому ловится только сборкой).
  always @(posedge clk) begin
    if (rst) begin
      for (i = 0; i < 6; i = i + 1) begin
        cnt[i]       <= 0;
        step[i]      <= 0;
        noise_cnt[i] <= 0;
        lfsr[i]      <= 18'h1;
      end
    end else if (cen) begin
      for (i = 0; i < 6; i = i + 1) begin
        if (lfo_on && lfo_rst && i == 1) begin
          // сброс источника: стоит в нуле, пока бит 7 держат
          cnt[1]  <= 0;
          step[1] <= 0;
        end else if (cnt[i] == 12'd0) begin
          // каналы 0 и 1 берут период у LFO, остальные — свой
          cnt[i]  <= (i == 0) ? per0 : (i == 1) ? per1 : freq[i];
          step[i] <= step[i] + 1'b1;
        end else begin
          cnt[i] <= cnt[i] - 1'b1;
        end
      end
      for (i = 4; i < 6; i = i + 1) begin
        if (noise_cnt[i] == 12'd0) begin
          // Период = 64 * (32 - nf) тактов чипа. Формула снята с
          // эталонной реализации: там шаг ((clk/rate)*32)/(32-nf)
          // накапливается до 0x800 за выборку, что даёт ровно это.
          // Подбор по спектру до этого дал вдвое худший результат —
          // широкополосный шум слишком грубо мерить центром тяжести.
          noise_cnt[i] <= {~noise_fq[i], 6'd0} + 12'd64;
          lfsr[i] <= {lfsr[i][0] ^ lfsr[i][1] ^ lfsr[i][11] ^ lfsr[i][12]
                      ^ lfsr[i][17], lfsr[i][17:1]};
        end else begin
          noise_cnt[i] <= noise_cnt[i] - 1'b1;
        end
      end
    end
  end

  // ------------------------------------------------------------------
  // Громкость. Модель снята с эталонной реализации (Ootake_PSG.c):
  //
  //     громкость = таблица[ канал + (главная + баланс) * 2 ]
  //     таблица[i] = 32768 * 10^((91 - i) * -1.0869 / 20)
  //
  // То есть шаг громкости КАНАЛА — 1.0869 дБ, а шаги главной громкости и
  // баланса ровно вдвое крупнее. Проверено ступенчатым тоном: эталон
  // ложится на эту формулу с точностью до сотых.
  //
  // Здесь раньше стояла шкала 1.5 дБ на шаг с четырёхбитными полями через
  // отдельную таблицу scale4. Она заметно круче эталонной, и всё, что
  // играет не на полной громкости, выходило тише: на середине шкалы на
  // 6 дБ, на громкости канала 4 — на 14. Из-за этого общий множитель
  // чипа, выведенный по картриджным рипам, не подходил рипам с CD, и те
  // выбивались вверх (задача 86).
  //
  // Индекс здесь — ЗАТУХАНИЕ (91 минус сумма громкостей): 0 максимум.
  // Таблица в 1/4095 долях, ниже -72 дБ обнуляется — у эталона там ещё
  // два десятка ступеней, но они и так за порогом слышимости.
  reg [11:0] att_tab[0:91];
  initial begin
    att_tab[ 0] = 12'd4095;  att_tab[ 1] = 12'd3613;  att_tab[ 2] = 12'd3188;  att_tab[ 3] = 12'd2813;
    att_tab[ 4] = 12'd2482;  att_tab[ 5] = 12'd2190;  att_tab[ 6] = 12'd1933;  att_tab[ 7] = 12'd1705;
    att_tab[ 8] = 12'd1505;  att_tab[ 9] = 12'd1328;  att_tab[10] = 12'd1172;  att_tab[11] = 12'd1034;
    att_tab[12] = 12'd 912;  att_tab[13] = 12'd 805;  att_tab[14] = 12'd 710;  att_tab[15] = 12'd 627;
    att_tab[16] = 12'd 553;  att_tab[17] = 12'd 488;  att_tab[18] = 12'd 431;  att_tab[19] = 12'd 380;
    att_tab[20] = 12'd 335;  att_tab[21] = 12'd 296;  att_tab[22] = 12'd 261;  att_tab[23] = 12'd 230;
    att_tab[24] = 12'd 203;  att_tab[25] = 12'd 179;  att_tab[26] = 12'd 158;  att_tab[27] = 12'd 140;
    att_tab[28] = 12'd 123;  att_tab[29] = 12'd 109;  att_tab[30] = 12'd  96;  att_tab[31] = 12'd  85;
    att_tab[32] = 12'd  75;  att_tab[33] = 12'd  66;  att_tab[34] = 12'd  58;  att_tab[35] = 12'd  51;
    att_tab[36] = 12'd  45;  att_tab[37] = 12'd  40;  att_tab[38] = 12'd  35;  att_tab[39] = 12'd  31;
    att_tab[40] = 12'd  27;  att_tab[41] = 12'd  24;  att_tab[42] = 12'd  21;  att_tab[43] = 12'd  19;
    att_tab[44] = 12'd  17;  att_tab[45] = 12'd  15;  att_tab[46] = 12'd  13;  att_tab[47] = 12'd  11;
    att_tab[48] = 12'd  10;  att_tab[49] = 12'd   9;  att_tab[50] = 12'd   8;  att_tab[51] = 12'd   7;
    att_tab[52] = 12'd   6;  att_tab[53] = 12'd   5;  att_tab[54] = 12'd   5;  att_tab[55] = 12'd   4;
    att_tab[56] = 12'd   4;  att_tab[57] = 12'd   3;  att_tab[58] = 12'd   3;  att_tab[59] = 12'd   3;
    att_tab[60] = 12'd   2;  att_tab[61] = 12'd   2;  att_tab[62] = 12'd   2;  att_tab[63] = 12'd   2;
    att_tab[64] = 12'd   1;  att_tab[65] = 12'd   1;  att_tab[66] = 12'd   1;  att_tab[67] = 12'd   1;
    att_tab[68] = 12'd   1;  att_tab[69] = 12'd   1;  att_tab[70] = 12'd   1;  att_tab[71] = 12'd   1;
    att_tab[72] = 12'd   1;  att_tab[73] = 12'd   0;  att_tab[74] = 12'd   0;  att_tab[75] = 12'd   0;
    att_tab[76] = 12'd   0;  att_tab[77] = 12'd   0;  att_tab[78] = 12'd   0;  att_tab[79] = 12'd   0;
    att_tab[80] = 12'd   0;  att_tab[81] = 12'd   0;  att_tab[82] = 12'd   0;  att_tab[83] = 12'd   0;
    att_tab[84] = 12'd   0;  att_tab[85] = 12'd   0;  att_tab[86] = 12'd   0;  att_tab[87] = 12'd   0;
    att_tab[88] = 12'd   0;  att_tab[89] = 12'd   0;  att_tab[90] = 12'd   0;  att_tab[91] = 12'd   0;
  end

  // ------------------------------------------------------------------
  // Обход каналов: по одному за такт clk, старт по cen
  reg  [2:0] scan = 0;
  // Накопитель шире прежнего: таблица теперь в 1/4095 долях вместо
  // 1/255, поэтому одно слагаемое доходит до 16*4095 = 65520, а шесть
  // каналов до 393120. В прежние 18 бит это не влезало.
  reg signed [21:0] acc_l = 0, acc_r = 0;
  reg  [4:0] samp_q = 0;
  reg  [2:0] scan_q = 0;
  reg  [2:0] scan_q2 = 0;
  wire signed [18:0] term_l = $signed(centred) * $signed({1'b0, att_tab[vl_i]});
  wire signed [18:0] term_r = $signed(centred) * $signed({1'b0, att_tab[vr_i]});

  // Сумма громкостей: канал плюс удвоенные главная и баланс. Умножение на
  // два — отдельным сдвигом, а не внутри выражения-индекса: в
  // самоопределённом контексте ширина берётся по операнду и произведение
  // молча обрезается.
  wire [4:0] main_l2 = {main_l, 1'b0};
  wire [4:0] main_r2 = {main_r, 1'b0};
  wire [4:0] bal_l2  = {bal_l[scan_q], 1'b0};
  wire [4:0] bal_r2  = {bal_r[scan_q], 1'b0};
  wire [6:0] loud_l = {2'b0, vol[scan_q]} + {2'b0, main_l2} + {2'b0, bal_l2};
  wire [6:0] loud_r = {2'b0, vol[scan_q]} + {2'b0, main_r2} + {2'b0, bal_r2};

  // Эталон глушит сторону, если её баланс нулевой, и весь канал, если
  // нулевая его собственная громкость. Без этого нулевой баланс давал бы
  // не тишину, а -32.6 дБ.
  // Канал 1 при включённом LFO молчит: он работает источником модуляции
  wire ch_mute = !ch_on[scan_q] || (lfo_on && scan_q == 3'd1)
              || vol[scan_q] == 5'd0;
  wire [6:0] vl_i = (ch_mute || bal_l[scan_q] == 4'd0) ? 7'd91 : (7'd91 - loud_l);
  wire [6:0] vr_i = (ch_mute || bal_r[scan_q] == 4'd0) ? 7'd91 : (7'd91 - loud_r);

  // шум подменяет волну на каналах 4-5
  wire noisy = (scan_q >= 3'd4) && noise_en[scan_q];
  wire [4:0] raw = ch_dda[scan_q] ? dda[scan_q]
                 : noisy ? (lfsr[scan_q][0] ? 5'd31 : 5'd0)
                 : samp_q;
  wire signed [5:0] centred = {1'b0, raw} - 6'sd16;

  always @(posedge clk) begin
    if (rst) begin
      scan <= 0;
      acc_l <= 0;
      acc_r <= 0;
      snd_left <= 0;
      snd_right <= 0;
    end else begin
      // Обход свободнобегущий, а не по cen: иначе он зависел бы от
      // соотношения частот ядра и чипа, и при малом числе тактов на cen
      // шесть каналов не успевали бы обсчитаться. Счётчики частоты
      // тикают по cen отдельно — высота тона от этого не зависит.
      scan <= (scan == 3'd5) ? 3'd0 : scan + 1'b1;

      // конвейер: адрес -> отсчёт -> накопление
      samp_q <= wave_ram[{scan, step[scan]}];
      // отсчёт канала-источника для LFO берём с того же прохода
      if (scan == 3'd1) lfo_wave <= wave_ram[{3'd1, step[1]}];
      scan_q <= scan;
      scan_q2 <= scan_q;

      // сумму начинаем нулевым каналом, а не обнулением по cen: иначе
      // обнуление и накопление конфликтовали бы в одном блоке
      if (scan_q == 3'd0) begin
        acc_l <= {{3{term_l[18]}}, term_l};
        acc_r <= {{3{term_r[18]}}, term_r};
      end else begin
        acc_l <= acc_l + {{3{term_l[18]}}, term_l};
        acc_r <= acc_r + {{3{term_r[18]}}, term_r};
      end

      // шестой канал попадает в acc только на следующем такте
      if (scan_q2 == 3'd5) begin
        // Сдвиг на четыре возвращает прежний масштаб выхода: 4095/255 =
        // 16, то есть общий множитель чипа менять не пришлось бы. Но
        // кривая стала положе, так что уровень всё равно перевыверен —
        // см. huc_gain в фирмвари.
        snd_left  <= (acc_l >>> 4) > 22'sd32767 ? 16'sd32767
                   : (acc_l >>> 4) < -22'sd32768 ? -16'sh8000
                   : acc_l[19:4];
        snd_right <= (acc_r >>> 4) > 22'sd32767 ? 16'sd32767
                   : (acc_r >>> 4) < -22'sd32768 ? -16'sh8000
                   : acc_r[19:4];
      end
    end
  end


endmodule
